import {build} from 'esbuild';
import {writeFile} from 'node:fs/promises';

// Keep the worker self-contained: Obsidian distributes only main.js, and npm
// consumers must not need Vite/webpack-specific worker configuration.
const result=await build({entryPoints:['node_modules/maplibre-gl/dist/maplibre-gl-worker.mjs'],bundle:true,write:false,format:'iife',platform:'browser',target:'es2020',minify:true,legalComments:'inline',metafile:true});
if(Object.values(result.metafile.outputs).some(output=>output.imports.length))throw new Error('MapLibre worker must not import external code');
await writeFile('src/maplibre-worker-source.js','// Generated by scripts/build-maplibre-worker.mjs from the locked MapLibre dependency.\nexport default '+JSON.stringify(result.outputFiles[0].text)+';\n');
